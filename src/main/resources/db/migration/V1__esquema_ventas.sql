-- Baseline of the pre-security model. Existing development schemas are baselined
-- at version 1; this script runs only for a fresh schema. No existing data is deleted.
create table categorias (
 id number(19,0) generated by default as identity primary key,
 nombre varchar2(50 char) not null, descripcion varchar2(200 char), estado boolean not null,
 fecha_creacion timestamp(6) not null, fecha_modificacion timestamp(6)
);
create table clientes (
 id number(19,0) generated by default as identity primary key,
 dni varchar2(8 char) not null, nombres varchar2(100 char) not null,
 apellidos varchar2(100 char) not null, email varchar2(150 char) not null,
 telefono varchar2(15 char), direccion varchar2(250 char), estado boolean not null,
 fecha_creacion timestamp(6) not null, fecha_modificacion timestamp(6)
);
create table productos (
 id number(19,0) generated by default as identity primary key,
 nombre varchar2(50 char) not null, descripcion varchar2(200 char),
 precio number(38,2) not null, stock number(10,0) not null,
 categoria_id number(19,0) not null references categorias(id), estado boolean not null,
 fecha_creacion timestamp(6) not null, fecha_modificacion timestamp(6)
);
create table ventas (
 id number(19,0) generated by default as identity primary key,
 fecha timestamp(6) not null, total number(12,2) not null,
 estado varchar2(20 char) not null, cliente_id number(19,0) not null references clientes(id)
);
create table detalle_ventas (
 id number(19,0) generated by default as identity primary key,
 venta_id number(19,0) not null references ventas(id),
 producto_id number(19,0) not null references productos(id),
 cantidad number(10,0) not null, precio number(10,2) not null, subtotal number(12,2) not null
);
